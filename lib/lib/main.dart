void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  bool isInitialized = false;
  String errorMessage = '';

  try {
    // Firebase and Hive do not depend on each other, so they start together.
    await Future.wait([
      Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform),
      Hive.initFlutter(),
    ]);

    // All boxes open in parallel once Hive is ready.
    await Future.wait([
      Hive.openBox(HiveService.boxName),
      Hive.openBox('settingsBox'),
      Hive.openBox(HiveService.syncBoxName),
    ]);
    isInitialized = true;
  } catch (e) {
    errorMessage = e.toString();
  }

  runApp(
    HealthWearableApp(isInitialized: isInitialized, errorMessage: errorMessage),
  );
}

class HealthWearableApp extends StatelessWidget {
  final bool isInitialized;
  final String errorMessage;

  const HealthWearableApp({
    super.key,
    required this.isInitialized,
    required this.errorMessage,
  });

  @override
  Widget build(BuildContext context) {
    if (!isInitialized) {
      return MaterialApp(
        debugShowCheckedModeBanner: false,
        theme: VitalTheme.dark,
        home: InitializationErrorScreen(error: errorMessage),
      );
    }

    return ChangeNotifierProvider(
      create: (_) => HealthViewModel(),
      child: Builder(
        builder: (context) {
          // Only the theme mode matters here. Listening to the whole view
          // model would rebuild MaterialApp on every live heart-rate update.
          final themeMode = context.select<HealthViewModel, ThemeMode>(
            (vm) => vm.themeMode,
          );
          return MaterialApp(
            title: 'VitalSync Wearable',
            debugShowCheckedModeBanner: false,
            themeMode: themeMode,
            theme: VitalTheme.light,
            darkTheme: VitalTheme.dark,
            themeAnimationDuration: const Duration(milliseconds: 350),
            themeAnimationCurve: Curves.easeOutCubic,
            home: const MainNavigationWrapper(),
          );
        },
      ),
    );
  }
}

