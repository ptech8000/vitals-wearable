class _NavItem {
  const _NavItem(this.icon, this.label);
  final IconData icon;
  final String label;
}

class MainNavigationWrapper extends StatefulWidget {
  const MainNavigationWrapper({super.key});

  @override
  State<MainNavigationWrapper> createState() => _MainNavigationWrapperState();
}

class _MainNavigationWrapperState extends State<MainNavigationWrapper>
    with SingleTickerProviderStateMixin {
  static const List<_NavItem> _navItems = [
    _NavItem(Icons.dashboard_rounded, 'Home'),
    _NavItem(Icons.insights_rounded, 'History'),
    _NavItem(Icons.settings_rounded, 'Settings'),
    _NavItem(Icons.ios_share_rounded, 'Export'),
  ];

  int _currentIndex = 0;

  /// Tabs are built the first time they are opened, not all at start-up.
  final Set<int> _visited = {0};

  late final AnimationController _switchController = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 320),
    value: 1,
  );
  late final Animation<double> _switchCurve = CurvedAnimation(
    parent: _switchController,
    curve: Curves.easeOutCubic,
  );
  late final Animation<Offset> _switchSlide = Tween<Offset>(
    begin: const Offset(0, 0.015),
    end: Offset.zero,
  ).animate(_switchCurve);

  Widget _screenFor(int index) {
    switch (index) {
      case 0:
        return const DashboardScreen();
      case 1:
        return const HistoryScreen();
      case 2:
        return const SettingsScreen();
      default:
        return const ExportScreen();
    }
  }

  void _goTo(int index) {
    if (index == _currentIndex) return;
    HapticFeedback.selectionClick();
    setState(() {
      _currentIndex = index;
      _visited.add(index);
    });
    _switchController.forward(from: 0);
  }

  @override
  void dispose() {
    _switchController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      extendBody: true,
      body: AppNavigator(
        goToTab: _goTo,
        child: FadeTransition(
          opacity: _switchCurve,
          child: SlideTransition(
            position: _switchSlide,
            child: IndexedStack(
              index: _currentIndex,
              children: [
                for (var i = 0; i < _navItems.length; i++)
                  if (_visited.contains(i))
                    // Animations on hidden tabs are paused.
                    TickerMode(
                      enabled: i == _currentIndex,
                      child: _screenFor(i),
                    )
                  else
                    const SizedBox.shrink(),
              ],
            ),
          ),
        ),
      ),
      bottomNavigationBar: _FloatingNavBar(
        index: _currentIndex,
        items: _navItems,
        onTap: _goTo,
      ),
    );
  }
}

class _FloatingNavBar extends StatelessWidget {
  const _FloatingNavBar({
    required this.index,
    required this.items,
    required this.onTap,
  });
  final int index;
  final List<_NavItem> items;
  final ValueChanged<int> onTap;
  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    final bottomInset = MediaQuery.viewPaddingOf(context).bottom;
    const radius = 30.0;
    return Padding(
      padding: EdgeInsets.fromLTRB(20, 0, 20, math.max(bottomInset, 6) + 0),
      child: DecoratedBox(
        decoration: BoxDecoration(
          borderRadius: BorderRadius.circular(radius),
          boxShadow: [
            BoxShadow(
              color: Colors.black.withValues(alpha: p.isDark ? .4 : .14),
              blurRadius: 28,
              offset: const Offset(0, 12),
            ),
          ],
        ),
        child: ClipRRect(
          borderRadius: BorderRadius.circular(radius),
          child: BackdropFilter(
            filter: ImageFilter.blur(sigmaX: 20, sigmaY: 20),
            child: Container(
              height: 68,
              decoration: BoxDecoration(
                color: p.isDark
                    ? const Color(0xB3161B22)
                    : const Color(0xD9FFFFFF),
                borderRadius: BorderRadius.circular(radius),
                border: Border.all(
                  color: p.isDark
                      ? Colors.white.withValues(alpha: .1)
                      : Colors.black.withValues(alpha: .06),
                ),
              ),
              child: LayoutBuilder(
                builder: (context, constraints) {
                  final itemWidth = constraints.maxWidth / items.length;
                  return Stack(
                    children: [
                      AnimatedPositioned(
                        duration: const Duration(milliseconds: 340),
                        curve: Curves.easeOutCubic,
                        left: itemWidth * index + 6,
                        top: 7,
                        width: itemWidth - 12,
                        height: 52,
                        child: DecoratedBox(
                          decoration: BoxDecoration(
                            color: VitalColors.primary.withValues(alpha: .16),
                            borderRadius: BorderRadius.circular(22),
                          ),
                        ),
                      ),
                      Row(
                        children: [
                          for (var i = 0; i < items.length; i++)
                            Expanded(
                              child: _NavButton(
                                item: items[i],
                                selected: i == index,
                                onTap: () => onTap(i),
                              ),
                            ),
                        ],
                      ),
                    ],
                  );
                },
              ),
            ),
          ),
        ),
      ),
    );
  }
}

class _NavButton extends StatelessWidget {
  const _NavButton({
    required this.item,
    required this.selected,
    required this.onTap,
  });
  final _NavItem item;
  final bool selected;
  final VoidCallback onTap;
  @override
  Widget build(BuildContext context) {
    final p = context.palette;
    final color = selected ? VitalColors.primary : p.textSecondary;
    return GestureDetector(
      behavior: HitTestBehavior.opaque,
      onTap: onTap,
      child: Semantics(
        button: true,
        selected: selected,
        label: item.label,
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            AnimatedScale(
              scale: selected ? 1.14 : 1,
              duration: const Duration(milliseconds: 260),
              curve: Curves.easeOutBack,
              child: TweenAnimationBuilder<Color?>(
                tween: ColorTween(end: color),
                duration: const Duration(milliseconds: 240),
                builder: (context, value, _) =>
                    Icon(item.icon, size: 23, color: value),
              ),
            ),
            const SizedBox(height: 3),
            AnimatedDefaultTextStyle(
              duration: const Duration(milliseconds: 240),
              style: TextStyle(
                fontSize: 10.5,
                fontWeight: selected ? FontWeight.w700 : FontWeight.w500,
                color: color,
              ),
              child: Text(item.label),
            ),
          ],
        ),
      ),
    );
  }
}
